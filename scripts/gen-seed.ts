// Generates supabase/seed.sql from the app's curated data files.
// Run: npm run seed:gen
import { writeFileSync } from "node:fs";
import { DESTINATIONS } from "../src/data/destinations.ts";
import { GEM_SEEDS } from "../src/data/gems.ts";
import { EVENT_SEEDS } from "../src/data/events.ts";
import { COMMUNITY_SEEDS } from "../src/data/communities.ts";

/** Fixed id for the editorial "Orbis Team" account that owns starter gems. */
export const TEAM_ID = "00000000-0000-4000-8000-000000000001";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const arr = (a: string[]) => `array[${a.map(q).join(", ")}]::text[]`;

const out: string[] = [
  "-- Generated by scripts/gen-seed.ts. Do not edit by hand.",
  "-- Curated destinations, editorial starter gems by the Orbis Team account, and SAMPLE events.",
  "-- Remove sample events before launch: delete from public.events where source = 'sample';",
  "",
  "begin;",
  "",
  `insert into auth.users (id, email, aud, role) values (${q(TEAM_ID)}, 'team@orbis.invalid', 'authenticated', 'authenticated') on conflict (id) do nothing;`,
  `update public.profiles set handle = 'orbis_team', name = 'Orbis Team', bio = 'Starter picks from the Orbis editors.', onboarded = true, hue = 12 where id = ${q(TEAM_ID)};`,
  "",
];

for (const d of DESTINATIONS) {
  out.push(
    `insert into public.destinations (id, name, country, region, lat, lng, hidden_gem, popularity, styles, tagline, description, best_time, scene) values (` +
      [q(d.id), q(d.name), q(d.country), q(d.region), d.lat, d.lng, d.hiddenGem, d.popularity, arr(d.styles), q(d.tagline), q(d.description), q(d.bestTime), q(JSON.stringify(d.scene)) + "::jsonb"].join(", ") +
      `) on conflict (id) do update set name = excluded.name, country = excluded.country, region = excluded.region, lat = excluded.lat, lng = excluded.lng, hidden_gem = excluded.hidden_gem, popularity = excluded.popularity, styles = excluded.styles, tagline = excluded.tagline, description = excluded.description, best_time = excluded.best_time, scene = excluded.scene;`,
  );
}
out.push("");

for (const g of GEM_SEEDS) {
  out.push(
    `insert into public.gems (author_id, destination_id, name, description, tip, category, styles, lat, lng, country) select ` +
      [q(TEAM_ID), q(g.destinationId), q(g.name), q(g.description), q(g.tip), q(g.category), arr(g.styles), g.lat, g.lng, q(g.country)].join(", ") +
      ` where not exists (select 1 from public.gems where author_id = ${q(TEAM_ID)} and name = ${q(g.name)});`,
  );
}
out.push("");

for (const e of EVENT_SEEDS) {
  out.push(
    `insert into public.events (destination_id, city, category, title, summary, starts_at, ends_at, source, external_id) values (` +
      [q(e.destinationId), q(e.city), q(e.category), q(e.title), q(e.summary), `now() + interval '${e.startInDays} days'`, `now() + interval '${e.startInDays + e.lengthDays} days'`, "'sample'", q(e.key)].join(", ") +
      `) on conflict (source, external_id) do nothing;`,
  );
}
out.push("");

// Official starter communities: empty, with no members or posts.
for (const c of COMMUNITY_SEEDS) {
  out.push(
    `insert into public.communities (slug, name, description, category, destination_id, country, styles, hue, official) values (` +
      [q(c.slug), q(c.name), q(c.description), q(c.category), c.destinationId ? q(c.destinationId) : "null", q(c.country), arr(c.styles), c.hue, "true"].join(", ") +
      `) on conflict (slug) do nothing;`,
  );
}
out.push("", "commit;", "");

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n"));
console.log(`seed.sql: ${DESTINATIONS.length} destinations, ${GEM_SEEDS.length} gems, ${EVENT_SEEDS.length} sample events, ${COMMUNITY_SEEDS.length} communities`);
